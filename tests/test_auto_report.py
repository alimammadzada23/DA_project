"""Automatic analysis report: formatting rules, structure, escaping and the Excel workbook."""
import io
import re

import openpyxl
import pytest

from insightpilot.universal import Workspace
from insightpilot.universal import auto_analysis as aa
from insightpilot.universal.auto_report import excel_report, format_value, html_report


@pytest.fixture(scope='module')
def output(tmp_path_factory):
    folder = tmp_path_factory.mktemp('report')
    path = folder / 'hostile.csv'
    rows = ['label,amount,outcome']
    for i in range(120):
        label = ['<script>alert(1)</script>', '=HYPERLINK(1)', 'plain'][i % 3]
        rows.append(f'{label},{i % 17},{"yes" if i % 4 == 0 else "no"}')
    path.write_text('\n'.join(rows) + '\n')
    workspace = Workspace.create(folder / 'w'); workspace.add_file(path, 'hostile')
    return aa.run(workspace, 'hostile', target='outcome', target_type='binary', positive='yes', save_evidence=False)


def visible(html):
    return re.sub(r'<script.*?</script>', '', html, flags=re.S)


@pytest.mark.parametrize('value,kind,expected', [(1234567, 'count', '1,234,567'), (0.4271, 'percent', '42.7%'), (0.00005, 'p', '5.00e-05'),
                                                 (0.0123, 'p', '0.012'), (0.0, 'p', '< 1e-300'), (0.41011, 'effect', '0.410'),
                                                 (64.425, 'number', '64.425'), (2515538.0, 'number', '2,515,538'), (0.000123, 'number', '0.000123'),
                                                 (None, 'number', '—'), (float('nan'), 'percent', '—'), ('Yes', 'text', 'Yes')])
def test_number_formatting(value, kind, expected):
    assert format_value(value, kind) == expected


def test_report_structure_in_order(output):
    html = html_report(output)
    headings = re.findall(r'<h2 id="section-([a-z]+)">', html)
    assert headings == ['quality', 'corrections', 'target', 'ranking', 'fields', 'relationships', 'method', 'evidence', 'conclusions']
    for text in ('Upload SHA-256', output['source_sha256'], 'Positive class', 'Analysed version', 'Analyst conclusions',
                 'Statistical associations are not causes', 'Benjamini–Hochberg'):
        assert text in html
    assert re.search(r'<div class="conclusions"></div>', html)


def test_hostile_values_are_escaped(output):
    html = visible(html_report(output))
    assert '<script>alert(1)</script>' not in html and '&lt;script&gt;alert(1)&lt;/script&gt;' in html


def test_charts_are_embedded_once_and_open_offline(output):
    html = html_report(output)
    assert html.count('plotly.js v') == 1
    assert not re.search(r'<script[^>]+src=', html) and not re.search(r'<link[^>]+href=', html)


def test_no_tool_markers_or_interpretive_words(output):
    text = re.sub(r'<[^>]+>', ' ', visible(html_report(output))).lower()
    for word in ('insightpilot', 'generated by', 'artificial intelligence', ' ai ', 'strong', 'important', 'significant', 'recommend', 'we suggest'):
        assert word not in text


def test_failed_stages_are_listed_at_the_top(output):
    failed = dict(output, stages=output['stages'] + [{'key': 'time', 'title': 'Time analysis', 'status': 'failed', 'error': 'ValueError: planted', 'seconds': 0}])
    html = html_report(failed)
    assert html.index('Failed stages') < html.index('section-quality') and 'ValueError: planted' in html


def test_every_table_has_evidence_in_the_appendix(output):
    html = html_report(output)
    appendix = html[html.index('id="section-evidence"'):]
    tables = [i for i in aa.iter_items(output) if i['type'] in ('table', 'figure')]
    assert appendix.count('<details>') == len(tables)
    assert output['analysis_version'] in appendix and 'SELECT' in appendix


def test_excel_has_one_sheet_per_table_with_safe_cells(output):
    book = openpyxl.load_workbook(io.BytesIO(excel_report(output)))
    tables = [i for i in aa.iter_items(output) if i['type'] == 'table']
    assert len(book.sheetnames) == len(tables) + 6 + 4   # overview, method tables, contents, evidence, conclusions
    assert all(len(name) <= 31 for name in book.sheetnames) and len(set(book.sheetnames)) == len(book.sheetnames)
    assert book.sheetnames[0] == 'Overview' and book.sheetnames[-1] == 'Analyst conclusions'
    values = [cell.value for sheet in book for row in sheet.iter_rows() for cell in row if isinstance(cell.value, str)]
    assert not any(v.lstrip().startswith(('=', '+', '-', '@')) for v in values)
    assert any(v.startswith("'=HYPERLINK") for v in values)
    rates = book[next(name for name in book.sheetnames if name.startswith('label  rows and positive'))]
    header = [c.value for c in rates[1]]
    assert rates.cell(row=2, column=header.index('Positive rate') + 1).number_format == '0.0%'
